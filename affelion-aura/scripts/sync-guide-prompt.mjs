/**
 * Writes the guide's system prompt into the Sasha server, so the server owns it and never has
 * to trust one sent by a client. The prompt is built from the colour knowledge base in this app,
 * which stays the single source of truth. Run after changing the knowledge base or the prompt:
 *
 *   npm run sync:guide-prompt
 *
 * `__tests__/guide.test.ts` fails if the two drift apart.
 */
import { build } from 'esbuild';
import { createRequire } from 'node:module';
import { mkdtempSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const out = join(mkdtempSync(join(tmpdir(), 'guide-prompt-')), 'guide.cjs');
await build({ entryPoints: [join(here, '..', 'src', 'services', 'ai', 'guide.ts')], bundle: true, format: 'cjs', platform: 'node', outfile: out, logLevel: 'silent' });
const { GUIDE_SYSTEM_PROMPT } = createRequire(import.meta.url)(out);
const target = join(here, '..', '..', 'server', 'sasha', 'src', 'systemPrompt.ts');
writeFileSync(
  target,
  `// Generated by affelion-aura/scripts/sync-guide-prompt.mjs from the app's colour knowledge base.\n// Do not edit by hand; run \`npm run sync:guide-prompt\` in affelion-aura instead.\nexport const SYSTEM_PROMPT = ${JSON.stringify(GUIDE_SYSTEM_PROMPT)};\n`,
);
console.log(`wrote ${target} (${GUIDE_SYSTEM_PROMPT.length} characters)`);
